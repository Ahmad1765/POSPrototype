// Adyen Webhook / Notification Schema (Async QR / Payment Events)
export interface AdyenNotificationRequestItem {
  additionalData: {
    'shopperReference'?: string;
    'authCode'?: string;
    'cardSummary'?: string;
    'paymentMethod'?: string;
    'expiryDate'?: string;
    'offline'?: string;
    [key: string]: string | undefined;
  };
  amount: {
    currency: string;
    value: number; // In minor units (cents / paise)
  };
  eventCode: 'AUTHORISATION' | 'CANCELLATION' | 'REFUND' | 'ORDER_OPENED' | 'PAYMENT_CAPTURED';
  eventDate: string;
  merchantAccountCode: string;
  merchantReference: string;
  paymentMethod: string;
  pspReference: string;
  reason?: string;
  success: 'true' | 'false';
  operations?: string[];
}

export interface AdyenWebhookNotification {
  live: 'true' | 'false';
  notificationItems: {
    NotificationRequestItem: AdyenNotificationRequestItem;
  }[];
}

// Adyen Terminal Hardware Profiles
